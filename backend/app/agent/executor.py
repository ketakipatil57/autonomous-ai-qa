"""Test executor for generating pytest files from TestPlan and running them.

Translates validated TestCase actions into deterministic Playwright calls,
executes pytest with pytest-json-report, and collects structured TestOutcome records.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

from backend.app.agent.evidence import update_evidence_failure
from backend.app.agent.plan_models import Action, TestCase, TestPlan, TestOutcome
from backend.app.config import settings


def sanitize_tc_id(tc_id: str) -> str:
    """Convert test code to valid Python identifier (e.g. TC-01 -> TC_01)."""
    return tc_id.replace("-", "_").replace(" ", "_")


def action_to_code(action: Action) -> str:
    """Translate an Action into a fixed Playwright call."""
    t = action.type
    target = action.target
    val = action.value

    if t == "goto":
        return f'runner.goto({val!r})'
    elif t == "fill":
        return f'runner.fill({target!r}, {val!r})'
    elif t == "click":
        return f'runner.click({target!r})'
    elif t == "expect_text":
        return f'runner.expect_text({target!r}, {val!r})'
    elif t == "expect_url":
        return f'runner.expect_url({val!r})'
    elif t == "expect_visible":
        return f'runner.expect_visible({target!r})'
    elif t == "expect_not_visible":
        return f'runner.expect_not_visible({target!r})'
    elif t == "expect_count_text":
        return f'runner.expect_count_text({target!r}, {val!r})'
    else:
        raise ValueError(f"Unsupported action type: {t}")


def generate_test_content(session_id: str, tc: TestCase) -> str:
    """Generate Python source code for a single pytest test function."""
    safe_id = sanitize_tc_id(tc.id)
    repo_root = str(settings.BASE_DIR)

    step_lines = []
    for step in tc.steps:
        code_stmt = action_to_code(step)
        step_lines.append(f"        {code_stmt}")

    steps_block = "\n".join(step_lines) if step_lines else "        pass"

    return f'''# Auto-generated by Autonomous AI QA Agent
import sys
from pathlib import Path

REPO_ROOT = Path(r"""{repo_root}""")
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from backend.app.agent.runner_lib import PlaywrightTestSession

def test_{safe_id}():
    """{tc.title} - {tc.expected}"""
    with PlaywrightTestSession(session_id="{session_id}", tc_id="{tc.id}") as runner:
{steps_block}
'''


class TestExecutor:
    """Generates and executes pytest suites for test sessions."""

    __test__ = False

    def __init__(
        self,
        generated_tests_root: Path | str | None = None,
        storage_root: Path | str | None = None,
    ):
        self.generated_tests_root = Path(generated_tests_root or settings.GENERATED_TESTS_DIR).resolve()
        self.storage_root = Path(storage_root or settings.STORAGE_DIR).resolve()

    def get_session_dir(self, session_id: str) -> Path:
        """Return directory path for generated test files in a session."""
        session_dir = self.generated_tests_root / session_id
        session_dir.mkdir(parents=True, exist_ok=True)
        return session_dir

    def generate_suite(self, session_id: str, plan: TestPlan) -> list[Path]:
        """Write all test cases in the plan to disk as pytest files."""
        session_dir = self.get_session_dir(session_id)
        generated_files = []

        for tc in plan.tests:
            safe_id = sanitize_tc_id(tc.id)
            test_file = session_dir / f"test_{safe_id}.py"
            content = generate_test_content(session_id, tc)
            with open(test_file, "w", encoding="utf-8") as f:
                f.write(content)
            generated_files.append(test_file)

        return generated_files

    def run_session(
        self,
        session_id: str,
        plan: TestPlan,
        timeout_seconds: int | None = None,
    ) -> list[TestOutcome]:
        """Generate test files and execute the full test session via pytest."""
        # 1. Generate pytest files
        self.generate_suite(session_id, plan)

        session_dir = self.get_session_dir(session_id)
        report_file = session_dir / "report.json"

        # 2. Execute pytest with pytest-json-report
        cmd = [
            sys.executable,
            "-m",
            "pytest",
            str(session_dir),
            "--json-report",
            f"--json-report-file={report_file}",
            "-p",
            "no:cacheprovider",
            "-v",
        ]

        env = os.environ.copy()
        env["PYTHONPATH"] = str(settings.BASE_DIR)

        timeout = timeout_seconds or settings.SESSION_TIMEOUT_SECONDS

        try:
            subprocess.run(
                cmd,
                cwd=str(settings.BASE_DIR),
                env=env,
                timeout=timeout,
                capture_output=True,
                text=True,
            )
        except subprocess.TimeoutExpired:
            # Session timed out
            pass

        # 3. Parse pytest json report into TestOutcome list
        return self._parse_report(session_id, plan, report_file)

    def run_single_test_case(
        self,
        session_id: str,
        test_case: TestCase,
        timeout_seconds: int | None = None,
    ) -> TestOutcome:
        """Run or recheck a single test case in its own pytest invocation."""
        session_dir = self.get_session_dir(session_id)
        safe_id = sanitize_tc_id(test_case.id)
        test_file = session_dir / f"test_{safe_id}.py"

        # Ensure file exists
        if not test_file.exists():
            content = generate_test_content(session_id, test_case)
            with open(test_file, "w", encoding="utf-8") as f:
                f.write(content)

        report_file = session_dir / f"report_{safe_id}.json"

        cmd = [
            sys.executable,
            "-m",
            "pytest",
            str(test_file),
            "--json-report",
            f"--json-report-file={report_file}",
            "-p",
            "no:cacheprovider",
        ]

        env = os.environ.copy()
        env["PYTHONPATH"] = str(settings.BASE_DIR)

        timeout = timeout_seconds or settings.TEST_TIMEOUT_SECONDS

        try:
            subprocess.run(
                cmd,
                cwd=str(settings.BASE_DIR),
                env=env,
                timeout=timeout,
                capture_output=True,
                text=True,
            )
        except subprocess.TimeoutExpired:
            pass

        single_plan = TestPlan(
            source="fallback",
            branch="instruction",
            tests=[test_case],
        )
        outcomes = self._parse_report(session_id, single_plan, report_file)
        if outcomes:
            return outcomes[0]

        return TestOutcome(
            tc_id=test_case.id,
            outcome="error",
            duration_ms=0.0,
            failure_message="Execution failed or timed out without report",
        )

    def _parse_report(
        self,
        session_id: str,
        plan: TestPlan,
        report_file: Path,
    ) -> list[TestOutcome]:
        """Parse pytest-json-report and correlate with TestCase definitions."""
        outcomes = []
        tc_map = {sanitize_tc_id(tc.id): tc for tc in plan.tests}
        parsed_tests = {}

        if report_file.exists():
            try:
                with open(report_file, "r", encoding="utf-8") as f:
                    report_data = json.load(f)

                for item in report_data.get("tests", []):
                    nodeid = item.get("nodeid", "")
                    # nodeid e.g. "generated_tests/session_1/test_TC_01.py::test_TC_01"
                    func_name = nodeid.split("::")[-1] if "::" in nodeid else nodeid
                    raw_id = func_name.replace("test_", "")
                    parsed_tests[raw_id] = item
            except Exception:
                pass

        for safe_id, tc in tc_map.items():
            test_entry = parsed_tests.get(safe_id)
            if not test_entry:
                # Test did not run or crashed before report
                outcomes.append(
                    TestOutcome(
                        tc_id=tc.id,
                        outcome="error",
                        duration_ms=0.0,
                        failure_message="Test did not execute or setup failed",
                    )
                )
                continue

            raw_outcome = test_entry.get("outcome", "error")
            outcome = "passed" if raw_outcome == "passed" else "failed"
            duration_sec = test_entry.get("duration", 0.0)
            duration_ms = round(duration_sec * 1000.0, 2)

            failure_message = None
            traceback_summary = None

            call_section = test_entry.get("call", {})
            if outcome == "failed" or raw_outcome != "passed":
                outcome = "failed"
                crash = call_section.get("crash", {})
                failure_message = crash.get("message")
                longrepr = call_section.get("longrepr") or test_entry.get("setup", {}).get("longrepr")
                traceback_summary = str(longrepr) if longrepr else None

                if not failure_message and traceback_summary:
                    # Use last line of traceback as summary
                    lines = [ln.strip() for ln in traceback_summary.splitlines() if ln.strip()]
                    failure_message = lines[-1] if lines else "Test assertion failed"

                # Check evidence directory
                tc_storage = self.storage_root / session_id / tc.id
                screenshot_file = tc_storage / "failure.png"
                evidence_file = tc_storage / "evidence.json"

                if failure_message:
                    update_evidence_failure(
                        session_id=session_id,
                        tc_id=tc.id,
                        failure_message=failure_message,
                        storage_root=self.storage_root,
                    )

                screenshot_path = str(screenshot_file) if screenshot_file.exists() else None
                evidence_path = str(evidence_file) if evidence_file.exists() else None
            else:
                screenshot_path = None
                evidence_path = None

            outcomes.append(
                TestOutcome(
                    tc_id=tc.id,
                    outcome=outcome,
                    duration_ms=duration_ms,
                    failure_message=failure_message,
                    traceback_summary=traceback_summary,
                    evidence_path=evidence_path,
                    screenshot_path=screenshot_path,
                )
            )

        return outcomes
