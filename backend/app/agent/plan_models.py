"""Pydantic schemas for test planning, exploration, actions, and execution outcomes."""

from __future__ import annotations

from typing import Any, Literal
from pydantic import BaseModel, Field, field_validator

ActionType = Literal[
    "goto",
    "fill",
    "click",
    "expect_text",
    "expect_url",
    "expect_visible",
    "expect_not_visible",
    "expect_count_text",
]

CategoryType = Literal["functional", "validation", "edge", "negative"]


class Action(BaseModel):
    """Single browser action step executed in Playwright."""

    type: ActionType
    target: str | None = None
    value: str | None = None


class TestCase(BaseModel):
    """Specification of an individual test case."""

    __test__ = False

    id: str = Field(..., description="Unique test code, e.g. TC-01")
    title: str
    category: CategoryType
    steps: list[Action] = Field(..., description="Ordered list of actions, maximum 15")
    expected: str = Field(..., description="Human-readable expected outcome")
    related_bug_hint: str | None = None

    @field_validator("steps")
    @classmethod
    def validate_steps_limit(cls, steps: list[Action]) -> list[Action]:
        if len(steps) > 15:
            raise ValueError(f"A test case cannot exceed 15 steps (got {len(steps)})")
        return steps


class TestPlan(BaseModel):
    """Plan of test cases generated by planner (OpenAI or deterministic fallback)."""

    __test__ = False

    source: Literal["openai", "fallback"]
    branch: Literal["instruction", "exploration"]
    tests: list[TestCase] = Field(..., description="List of test cases to execute, maximum 8")

    @field_validator("tests")
    @classmethod
    def validate_tests_limit(cls, tests: list[TestCase]) -> list[TestCase]:
        if len(tests) > 8:
            raise ValueError(f"A test plan cannot exceed 8 tests (got {len(tests)})")
        return tests


class TestOutcome(BaseModel):
    """Result of running a test case via pytest."""

    __test__ = False

    tc_id: str
    outcome: Literal["passed", "failed", "error"]
    duration_ms: float = 0.0
    failure_message: str | None = None
    traceback_summary: str | None = None
    evidence_path: str | None = None
    screenshot_path: str | None = None


# --- Exploration / SiteMap Schemas (Section 6.3) ---

class PageInput(BaseModel):
    """Extracted form input metadata."""

    type: str = "text"
    name: str | None = None
    id: str | None = None
    placeholder: str | None = None
    label: str | None = None


class PageButton(BaseModel):
    """Extracted clickable button metadata."""

    text: str
    id: str | None = None
    type: str = "button"
    selector: str | None = None


class PageForm(BaseModel):
    """Extracted HTML form metadata."""

    id: str | None = None
    action: str | None = None
    method: str = "GET"
    inputs: list[PageInput] = Field(default_factory=list)
    submit_button: str | None = None


class PageData(BaseModel):
    """Comprehensive snapshot of a discovered webpage during exploration."""

    url: str
    title: str
    links: list[str] = Field(default_factory=list)
    buttons: list[PageButton] = Field(default_factory=list)
    inputs: list[PageInput] = Field(default_factory=list)
    forms: list[PageForm] = Field(default_factory=list)
    headings: list[str] = Field(default_factory=list)


class SiteMap(BaseModel):
    """Full site map collected by explorer BFS crawl."""

    app_url: str
    pages: list[PageData] = Field(default_factory=list)
    explored_count: int = 0


# --- Verifier and Reporter Schemas (Section 6.8 & 6.9) ---

TestStatus = Literal["PASSED", "FAILED", "NEEDS_REVIEW"]
SeverityType = Literal["LOW", "MEDIUM", "HIGH"]


class TestResult(BaseModel):
    """Verified test outcome with status classification, reason, and recheck history."""

    __test__ = False

    id: str = Field(..., description="Unique test result UUID")
    session_id: str
    tc_id: str
    status: TestStatus
    reason: str
    first_run_outcome: str
    recheck_outcome: str | None = None
    duration_ms: float = 0.0
    failure_message: str | None = None
    explanation: str | None = None
    screenshot_path: str | None = None
    evidence_path: str | None = None
    report_path: str | None = None


class BugReport(BaseModel):
    """Structured evidence-backed bug report for confirmed test failures."""

    id: str = Field(..., description="Report UUID or identifier")
    session_id: str
    tc_id: str
    test_result_id: str | None = None
    bug_code: str = Field(..., description="Display code, e.g. BUG-session-1")
    title: str
    severity: SeverityType
    reproduction_steps: list[str] = Field(default_factory=list)
    expected: str
    actual: str
    status: str = "CONFIRMED"
    environment: dict[str, Any] = Field(default_factory=dict)
    evidence: dict[str, Any] = Field(default_factory=dict)
    report_path: str | None = None
    created_at: str
